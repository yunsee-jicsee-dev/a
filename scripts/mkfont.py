#!/usr/bin/env python3
"""Turn a PSF console font into src/font8x16.h (printable ASCII only).

    python3 scripts/mkfont.py /usr/share/consolefonts/Lat15-TerminusBold16.psf.gz > src/font8x16.h
"""
import gzip, struct, sys

data = gzip.open(sys.argv[1]).read()
if data[:2] == b"\x36\x04":  # PSF1
    n, h, w, hdr = (512 if data[2] & 1 else 256), data[3], 8, 4
    has_tab, tab = bool(data[2] & 2), hdr + n * h
    def entries(pos):
        out = []
        for i in range(n):
            cps = []
            while True:
                (u,) = struct.unpack_from("<H", data, pos); pos += 2
                if u == 0xFFFF: break
                if u != 0xFFFE: cps.append(u)
            out.append(cps)
        return out
else:  # PSF2
    _, _, hdr, flags, n, size, h, w = struct.unpack_from("<8I", data)
    has_tab, tab = bool(flags & 1), hdr + n * size
    def entries(pos):
        out = []
        for i in range(n):
            end = data.index(b"\xff", pos)
            out.append([ord(c) for c in data[pos:end].decode("utf-8", "ignore")]); pos = end + 1
        return out
assert w == 8 and h == 16, (w, h)
glyph_of = {}
for i, cps in enumerate(entries(tab) if has_tab else [[i] for i in range(n)]):
    for cp in cps:
        glyph_of.setdefault(cp, i)
print("/* Terminus Bold 8x16, printable ASCII. Terminus Font (c) Dimitar Zhekov,")
print(" * SIL Open Font License 1.1. Generated by scripts/mkfont.py. */")
print("static const unsigned char FONT8X16[95][16] = {")
for cp in range(32, 127):
    g = glyph_of[cp]
    rows = data[hdr + g * h: hdr + g * h + h]
    print("\t{" + ", ".join("0x%02x" % b for b in rows) + "}, /* %r */" % chr(cp))
print("};")
